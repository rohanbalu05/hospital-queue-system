// Aggregates every <workspace>/coverage/coverage-summary.json into docs/evidence/coverage-summary.json
// and prints a markdown table. Run after `pnpm -r --if-present test:coverage` (see `pnpm coverage`).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, mdTable, pct, pkgName, readJson, stamp, workspaceDirs } from './lib.mjs';

export function collectCoverage() {
  const packages = {};
  const missing = [];
  for (const dir of workspaceDirs()) {
    const file = path.join(ROOT, dir, 'coverage', 'coverage-summary.json');
    if (!fs.existsSync(file)) {
      missing.push(dir);
      continue;
    }
    const total = readJson(file).total;
    packages[pkgName(dir)] = {
      dir,
      lines: total.lines,
      statements: total.statements,
      functions: total.functions,
      branches: total.branches,
    };
  }
  return { packages, missing };
}

export function coverageTable(packages) {
  const cell = (m) => `${pct(m.pct)} (${m.covered}/${m.total})`;
  const rows = Object.entries(packages).map(([name, c]) => [
    name,
    cell(c.lines),
    cell(c.statements),
    cell(c.functions),
    cell(c.branches),
  ]);
  return mdTable(['Package', 'Lines', 'Statements', 'Functions', 'Branches'], rows);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { packages, missing } = collectCoverage();
  const out = {
    note: 'Measured by Vitest v8 coverage on the stated date, commit and machine. Generated by scripts/coverage-summary.mjs.',
    ...stamp(),
    packages,
    packagesWithoutCoverage: missing,
  };
  fs.mkdirSync(path.join(ROOT, 'docs/evidence'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'docs/evidence/coverage-summary.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(coverageTable(packages));
  if (missing.length) console.log(`\nNo coverage report yet for: ${missing.join(', ')}`);
}

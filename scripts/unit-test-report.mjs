// `pnpm evidence:tests`: runs each package's Vitest suite with the JSON reporter and writes
// docs/evidence/unit-tests.md (counts, durations, per-file suites, coverage table).
// Coverage numbers are read from docs/evidence/coverage-summary.json (produced by `pnpm coverage`).
// DB-backed suites (packages/db, apps/worker, apps/api) need PostgreSQL at TEST_DATABASE_URL.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ROOT, mdTable, readJson, run, stamp, toolVersion, workspaceDirs } from './lib.mjs';
import { coverageTable } from './coverage-summary.mjs';

const st = stamp();
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hqms-vitest-'));

// What each suite is for (package role); the per-file breakdown below is generated from the run.
const ROLE = {
  '@hqms/domain':
    'Pure queue policy: eligibility, the Table 8 golden selection trace, rotation pointer, ETA/EWMA, lifecycle state machines, plus fast-check property tests (determinism, non-preemption) and a purity test.',
  '@hqms/contracts': 'zod request/response/event schemas: accepted and rejected payloads.',
  '@hqms/db':
    'Real-PostgreSQL tests of the migration runner, seed, transaction helper (lock order, bounded retry), idempotency records and capacity counters.',
  '@hqms/worker':
    'Real-PostgreSQL tests of the job runner (SKIP LOCKED leases), outbox dispatch and background handlers.',
  '@hqms/api': 'API module, guard and route tests.',
  '@hqms/web': 'Component and client-side logic tests.',
  '@hqms/tests':
    'Seeded FCFS-versus-policy simulation (DB-free). Integration (`tests/integration`) and concurrency (`tests/concurrency`, T1/T2) suites are run separately by `pnpm test:concurrency` and are NOT included here.',
};

const results = [];
for (const dir of workspaceDirs()) {
  const pkg = readJson(path.join(ROOT, dir, 'package.json'));
  const hasVitest = Object.values(pkg.devDependencies ?? {}).length && 'vitest' in (pkg.devDependencies ?? {});
  if (!pkg.scripts?.test || !hasVitest) continue;
  const outFile = path.join(tmp, `${dir.replaceAll('/', '_')}.json`);
  const args = ['exec', 'vitest', 'run', '--reporter=json', `--outputFile=${outFile}`];
  if (dir === 'tests') args.push('--config', 'simulation/vitest.config.ts');
  const t0 = Date.now();
  const r = run('pnpm', args, { cwd: path.join(ROOT, dir) });
  const wallMs = Date.now() - t0;
  let json = null;
  try {
    json = JSON.parse(fs.readFileSync(outFile, 'utf8'));
  } catch {
    /* handled below */
  }
  results.push({ dir, name: pkg.name, json, wallMs, exit: r.status, err: r.stderr.slice(-400) });
}

const rel = (p, dir) => path.relative(path.join(ROOT, dir), p).split(path.sep).join('/');
const sec = (ms) => `${(ms / 1000).toFixed(1)} s`;

let passed = 0;
let failed = 0;
let skipped = 0;
let total = 0;
const summaryRows = results.map((x) => {
  if (!x.json) return [x.name, 'n/a', 'n/a', 'n/a', 'n/a', sec(x.wallMs), `did not produce a report (exit ${x.exit})`];
  const j = x.json;
  const skip = (j.numPendingTests ?? 0) + (j.numTodoTests ?? 0);
  passed += j.numPassedTests;
  failed += j.numFailedTests;
  skipped += skip;
  total += j.numTotalTests;
  return [
    x.name,
    j.numTotalTests,
    j.numPassedTests,
    j.numFailedTests,
    skip,
    sec(x.wallMs),
    j.success ? 'pass' : 'FAIL',
  ];
});

let cov = null;
const covFile = path.join(ROOT, 'docs/evidence/coverage-summary.json');
if (fs.existsSync(covFile)) cov = readJson(covFile);

const out = [];
out.push('# Unit and integration test evidence', '');
out.push(
  `Generated by \`scripts/unit-test-report.mjs\` (\`pnpm evidence:tests\`). **Measured on ${st.date}, commit \`${st.hash}\`${st.dirty ? ' (working tree had uncommitted changes)' : ''}, branch \`${st.branch}\`, on this machine (${st.host}).** Counts come from Vitest's JSON reporter; durations are wall-clock per package including start-up and database set-up. Nothing here is a target.`,
  '',
);
out.push(
  `Tool: ${toolVersion('pnpm', ['exec', 'vitest', '--version'])}, coverage provider \`v8\` (\`@vitest/coverage-v8\`).`,
  '',
);
out.push('## Results per package', '');
out.push(mdTable(['Package', 'Tests', 'Passed', 'Failed', 'Skipped', 'Wall time', 'Status'], summaryRows), '');
out.push(`**Total: ${total} tests, ${passed} passed, ${failed} failed, ${skipped} skipped.**`, '');

out.push('## Coverage', '');
if (cov) {
  out.push(
    `Statement/line/function/branch coverage by Vitest v8, from \`docs/evidence/coverage-summary.json\` (measured ${cov.date}, commit \`${cov.hash}\`${cov.hash === st.hash ? '' : '; differs from the commit of the test run above'}). Re-measure with \`pnpm coverage\`. Coverage is over each package's \`src/\` (\`tests\`: the simulation engine), test files excluded.`,
    '',
  );
  out.push(coverageTable(cov.packages), '');
  if (cov.packagesWithoutCoverage?.length)
    out.push(
      `No coverage report yet for: ${cov.packagesWithoutCoverage.map((d) => `\`${d}\``).join(', ')} (add a \`test:coverage\` script to the package).`,
      '',
    );
} else out.push('Coverage not measured yet: run `pnpm coverage`, then re-run this generator.', '');

out.push('## What each suite covers', '');
for (const x of results) {
  out.push(`### ${x.name} (\`${x.dir}\`)`, '');
  out.push(ROLE[x.name] ?? 'No description recorded for this package; see the file list below.', '');
  if (!x.json) {
    out.push(
      `No JSON report was produced (exit ${x.exit}). Last stderr: \`${x.err.replaceAll('`', "'").replaceAll('\n', ' ')}\``,
      '',
    );
    continue;
  }
  const rows = x.json.testResults
    .map((f) => {
      const suites = [...new Set(f.assertionResults.map((a) => a.ancestorTitles?.[0]).filter(Boolean))];
      return [
        rel(f.name, x.dir),
        f.assertionResults.length,
        f.assertionResults.filter((a) => a.status === 'failed').length,
        suites.join('; ') || '-',
      ];
    })
    .sort((a, b) => a[0].localeCompare(b[0]));
  out.push(mdTable(['Test file', 'Tests', 'Failed', 'Top-level suites'], rows), '');
}

out.push('## How to reproduce', '');
out.push(
  '```bash',
  './init.sh                 # starts PostgreSQL, creates hqms and hqms_test (DB-backed suites need it)',
  'pnpm test                 # all package suites',
  'pnpm coverage             # test:coverage in every package, then docs/evidence/coverage-summary.json',
  'pnpm evidence:tests       # regenerates this file',
  '```',
  '',
);
fs.writeFileSync(path.join(ROOT, 'docs/evidence/unit-tests.md'), out.join('\n'));
fs.rmSync(tmp, { recursive: true, force: true });
console.log('wrote docs/evidence/unit-tests.md');
console.log(mdTable(['Package', 'Tests', 'Passed', 'Failed', 'Skipped', 'Wall time', 'Status'], summaryRows));
if (failed > 0 || results.some((x) => !x.json)) process.exitCode = 1;

// `pnpm evidence:static`: runs every static-analysis tool and writes docs/evidence/static-analysis.md.
// Every number in the output is parsed from a tool run made by this script; nothing is hand-written.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { ROOT, mdTable, readJson, run, stamp, toolVersion, workspaceDirs } from './lib.mjs';

const require = createRequire(import.meta.url);
const st = stamp();
const dirs = workspaceDirs();
const existing = ['apps', 'packages', 'tests'].filter((d) => fs.existsSync(path.join(ROOT, d)));

// 1. TypeScript strict typecheck, per package ---------------------------------------------------
const tsRows = [];
for (const dir of dirs) {
  const pkg = readJson(path.join(ROOT, dir, 'package.json'));
  if (!pkg.scripts?.typecheck) {
    tsRows.push([pkg.name, dir, 'no typecheck script', '-']);
    continue;
  }
  const r = run('pnpm', ['--filter', pkg.name, 'run', 'typecheck']);
  const errs = (r.stdout + r.stderr).split('\n').filter((l) => /error TS\d+/.test(l));
  tsRows.push([pkg.name, dir, r.status === 0 ? 'pass' : 'FAIL', String(errs.length)]);
}

// 2. ESLint (JSON formatter) --------------------------------------------------------------------
const es = run('pnpm', ['exec', 'eslint', '.', '--format', 'json']);
let eslint = null;
try {
  eslint = JSON.parse(es.stdout);
} catch {
  /* reported below */
}
const byRule = new Map();
const byPkg = new Map();
let eslintErrors = 0;
let eslintWarnings = 0;
if (eslint) {
  for (const f of eslint) {
    const rel = path.relative(ROOT, f.filePath).split(path.sep).join('/');
    const owner = dirs.find((d) => rel === d || rel.startsWith(`${d}/`)) ?? '(repo root and other)';
    const p = byPkg.get(owner) ?? { files: 0, errors: 0, warnings: 0 };
    p.files += 1;
    p.errors += f.errorCount;
    p.warnings += f.warningCount;
    byPkg.set(owner, p);
    eslintErrors += f.errorCount;
    eslintWarnings += f.warningCount;
    for (const m of f.messages) {
      const key = m.ruleId ?? '(parse/config error)';
      const r = byRule.get(key) ?? { errors: 0, warnings: 0 };
      if (m.severity === 2) r.errors += 1;
      else r.warnings += 1;
      byRule.set(key, r);
    }
  }
}

// 3. dependency-cruiser (JSON) ------------------------------------------------------------------
const dc = run('pnpm', [
  'exec',
  'depcruise',
  ...existing,
  '--config',
  '.dependency-cruiser.cjs',
  '--output-type',
  'json',
]);
let cruise = null;
try {
  cruise = JSON.parse(dc.stdout);
} catch {
  /* reported below */
}
const rules = require(path.join(ROOT, '.dependency-cruiser.cjs')).forbidden ?? [];
const violationsByRule = new Map();
for (const v of cruise?.summary.violations ?? [])
  violationsByRule.set(v.rule.name, (violationsByRule.get(v.rule.name) ?? 0) + 1);

// 4. Semgrep (JSON) -----------------------------------------------------------------------------
const sgArgs = [
  'scan',
  '--config',
  'p/typescript',
  '--config',
  'p/owasp-top-ten',
  '--json',
  '--time',
  '--metrics=off',
  '--quiet',
  '--exclude',
  'node_modules',
  '--exclude',
  'dist',
  '--exclude',
  'coverage',
  '--exclude',
  'fixtures',
  ...existing.filter((d) => d !== 'tests'),
];
const sg = run('semgrep', sgArgs);
let semgrep = null;
try {
  semgrep = JSON.parse(sg.stdout);
} catch {
  /* reported below */
}
const sgBySeverity = new Map();
for (const r of semgrep?.results ?? []) {
  const sev = r.extra?.severity ?? 'UNKNOWN';
  sgBySeverity.set(sev, (sgBySeverity.get(sev) ?? 0) + 1);
}

// 5. Configuration summary (read from the real config files) ------------------------------------
const tsBase = readJson(path.join(ROOT, 'tsconfig.base.json')).compilerOptions;
const strictFlags = [
  'strict',
  'noUncheckedIndexedAccess',
  'noImplicitOverride',
  'noFallthroughCasesInSwitch',
  'isolatedModules',
  'forceConsistentCasingInFileNames',
]
  .filter((k) => k in tsBase)
  .map((k) => `\`${k}: ${tsBase[k]}\``)
  .join(', ');

const ok = (b) => (b ? 'ran' : 'DID NOT RUN (see output below)');
const out = [];
out.push('# Static analysis evidence', '');
out.push(
  `Generated by \`scripts/static-analysis-report.mjs\` (\`pnpm evidence:static\`). **Measured** on ${st.date}, commit \`${st.hash}\`${st.dirty ? ' (working tree had uncommitted changes)' : ''}, branch \`${st.branch}\`, ${st.host}. All counts below were parsed from tool output of this run; none are hand-written. Re-run to refresh.`,
  '',
);
out.push('## Tool versions', '');
out.push(
  mdTable(
    ['Tool', 'Version'],
    [
      ['TypeScript (tsc)', run('pnpm', ['exec', 'tsc', '--version']).stdout.trim()],
      ['ESLint', run('pnpm', ['exec', 'eslint', '--version']).stdout.trim()],
      ['typescript-eslint', readJson(path.join(ROOT, 'node_modules/typescript-eslint/package.json')).version],
      ['dependency-cruiser', run('pnpm', ['exec', 'depcruise', '--version']).stdout.trim().split('\n').pop()],
      ['Semgrep', toolVersion('semgrep')],
      ['Node', process.version],
    ],
  ),
  '',
);

out.push('## Configuration', '');
out.push('### TypeScript', '');
out.push(
  `All packages extend \`tsconfig.base.json\`. Strictness flags in force: ${strictFlags}. Each package typechecks with \`tsc --noEmit\` through its own \`typecheck\` script; no \`any\` escape hatches are configured at compiler level.`,
  '',
);
out.push('### ESLint', '');
out.push(
  'Flat config in `eslint.config.js`: `@eslint/js` recommended + `typescript-eslint` **strict** rule set (syntactic, not type-aware; type errors are the job of `tsc`). Extra rules: `eqeqeq` (always), `no-console` (warn; allowed in tests, scripts, db, worker and the api entry point), `consistent-type-imports`, `no-unused-vars` (underscore-prefixed names ignored). Run with `--max-warnings 0`, so any warning fails `pnpm verify`. Generated shadcn/ui components, build output and coverage output are ignored.',
  '',
);
out.push('### dependency-cruiser (architecture rules)', '');
out.push(
  'Defined in `.dependency-cruiser.cjs`. In words: **domain purity** (`packages/domain/src` imports nothing outside itself, not even node built-ins or npm packages); **apps isolation** (no `apps/*` package imports another app); **web depends on contracts only** (`apps/web` may not import api, worker, db or domain); packages never import apps; `contracts` is a leaf; `db` does not import `domain`; **no circular dependencies** anywhere. Rules in force:',
  '',
);
out.push(
  mdTable(
    ['Rule', 'Severity', 'Violations this run'],
    rules.map((r) => [r.name, r.severity, cruise ? String(violationsByRule.get(r.name) ?? 0) : 'n/a']),
  ),
  '',
);
out.push('### Semgrep', '');
out.push(
  'Rulesets `p/typescript` and `p/owasp-top-ten` from the Semgrep registry, run with `--error` in `pnpm verify` (any finding fails the build), metrics off. Scope: `apps/` and `packages/` source, excluding `node_modules`, `dist`, `coverage` and test `fixtures`.',
  '',
);

out.push('## Results', '');
out.push('### TypeScript strict typecheck', '');
out.push(mdTable(['Package', 'Path', 'Result', 'TS errors'], tsRows), '');

out.push('### ESLint', '');
if (eslint) {
  out.push(`Files linted: ${eslint.length}. Errors: **${eslintErrors}**. Warnings: **${eslintWarnings}**.`, '');
  out.push(
    mdTable(
      ['Package / area', 'Files linted', 'Errors', 'Warnings'],
      [...byPkg.entries()].sort().map(([k, v]) => [k, v.files, v.errors, v.warnings]),
    ),
    '',
  );
  if (byRule.size) {
    out.push('Findings by rule:', '');
    out.push(
      mdTable(
        ['Rule', 'Errors', 'Warnings'],
        [...byRule.entries()]
          .sort((a, b) => b[1].errors + b[1].warnings - (a[1].errors + a[1].warnings))
          .map(([k, v]) => [k, v.errors, v.warnings]),
      ),
      '',
    );
  } else out.push('Findings by rule: none (no rule produced a message).', '');
} else out.push(`ESLint ${ok(false)}: ${es.stderr.slice(0, 500)}`, '');

out.push('### dependency-cruiser', '');
if (cruise) {
  const s = cruise.summary;
  out.push(
    mdTable(
      ['Metric', 'Value'],
      [
        ['Modules cruised', s.totalCruised],
        ['Dependencies cruised', s.totalDependenciesCruised],
        ['Violations (total)', s.violations.length],
        ['Errors', s.error],
        ['Warnings', s.warn],
        ['Rules evaluated', rules.length],
      ],
    ),
    '',
  );
  if (s.violations.length) {
    out.push('Violations:', '');
    for (const v of s.violations) out.push(`- \`${v.rule.name}\`: \`${v.from}\` -> \`${v.to}\``);
    out.push('');
  }
} else out.push(`dependency-cruiser ${ok(false)}: ${dc.stderr.slice(0, 500)}`, '');

out.push('### Semgrep', '');
if (semgrep) {
  out.push(
    mdTable(
      ['Metric', 'Value'],
      [
        [
          'Rules run (p/typescript + p/owasp-top-ten, applicable to scanned languages)',
          semgrep.time?.rules?.length ?? 'n/a',
        ],
        ['Files scanned', semgrep.paths?.scanned?.length ?? 'n/a'],
        ['Findings (total)', semgrep.results.length],
        ['Findings: ERROR', sgBySeverity.get('ERROR') ?? 0],
        ['Findings: WARNING', sgBySeverity.get('WARNING') ?? 0],
        ['Findings: INFO', sgBySeverity.get('INFO') ?? 0],
        ['Scan errors', semgrep.errors.length],
      ],
    ),
    '',
  );
  if (semgrep.results.length) {
    out.push('Findings:', '');
    for (const r of semgrep.results)
      out.push(`- [${r.extra?.severity}] \`${r.check_id}\` at \`${r.path}:${r.start?.line}\``);
    out.push('');
  }
} else out.push(`Semgrep ${ok(false)}: ${sg.stderr.slice(0, 500)}`, '');

out.push('## Scope and limits', '');
out.push(
  '- Packages are discovered from the workspace at run time (`apps/*`, `packages/*`, `tests`); a package that does not exist yet (for example `apps/api` before it is merged) simply does not appear. Re-run after each merge to refresh.',
  '- ESLint runs the syntactic strict set only; type-aware lint rules are not enabled.',
  '- Semgrep reports pattern-based findings; a clean run is evidence of no matches for those rulesets, not proof of absence of vulnerabilities. Dynamic and penetration evidence belong in `docs/evidence/dynamic-analysis.md` and the T-series files.',
  '',
);
out.push('## How to reproduce', '');
out.push(
  '```bash',
  'pnpm install',
  'pip install semgrep          # or: pipx install semgrep',
  'pnpm evidence:static         # regenerates this file',
  '',
  '# individual tools, as run by `pnpm verify`:',
  'pnpm typecheck               # tsc --noEmit in every package',
  'pnpm lint                    # eslint . --max-warnings 0',
  'pnpm depcruise               # architecture rules',
  'pnpm semgrep                 # --config p/typescript --config p/owasp-top-ten --error',
  '```',
  '',
);

fs.mkdirSync(path.join(ROOT, 'docs/evidence'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/evidence/static-analysis.md'), out.join('\n'));
console.log('wrote docs/evidence/static-analysis.md');
console.log(`typecheck: ${tsRows.map((r) => `${r[0]}=${r[2]}`).join(', ')}`);
console.log(
  `eslint: errors=${eslintErrors} warnings=${eslintWarnings}; depcruise violations=${cruise?.summary.violations.length ?? 'n/a'}; semgrep findings=${semgrep?.results.length ?? 'n/a'}`,
);
